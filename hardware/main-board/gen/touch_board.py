"""HA panel touch board (rev D, decision 5A) - schematic (KiCad 9). Run: python3 touch_board.py <outdir>"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kicadgen as kg
import lib_ha_panel
import footprints

OUT = sys.argv[1] if len(sys.argv) > 1 else '/home/claude/work/out/touch-board'
DATE = '2026-11-07'
R0603 = 'Resistor_SMD:R_0603_1608Metric'
C0603 = 'Capacitor_SMD:C_0603_1608Metric'
DS_QT = 'https://ww1.microchip.com/downloads/en/DeviceDoc/Atmel-9596-AT42-QTouch-BSW-AT42QT1070_Datasheet.pdf'


def F(mpn='', mfr='', dk='', spec='', note=''):
    d = {}
    if mpn: d['MPN'] = mpn
    if mfr: d['Manufacturer'] = mfr
    if dk: d['DigiKey'] = dk
    if spec: d['Spec'] = spec
    if note: d['Note'] = note
    return d


def design(prj):
    s = prj.root
    s.text('TOUCH BOARD rev D (decision 5A): 4 electrodes + AT42QT1070, one HOST wire-pad set; replaces rev C in the chin seat',
           20.32, 15.24, size=1.8, bold=True)
    s.comp('J1', 'Connector_Generic:Conn_01x04', 'HOST (wire pads)', (30.48, 78.74),
           nets={'1': '+3V3', '2': 'GND', '3': 'SDA', '4': 'SCL'}, footprint='ha_panel:WirePads_1x04_P3.50mm_2.0x3.0mm',
           in_bom=False, fields=F(note='SMD pads on the back: lead from main board J6 (XH 4P, cut end): 1 VCC 3.3 V, 2 GND, '
                                       '3 SDA, 4 SCL'))
    s.pwr_flag('+3V3', (50.8, 45.72))
    s.pwr_flag('GND', (63.5, 45.72))
    s.comp('C1', 'Device:C', '100n 50V', (76.2, 63.5), nets={'1': '+3V3', '2': 'GND'}, footprint=C0603,
           fields=F(spec='100 nF 50 V X7R 0603', note='VDD decoupling at pin 1'))
    s.comp('C2', 'Device:C', '10u 10V', (88.9, 63.5), nets={'1': '+3V3', '2': 'GND'}, footprint=C0603,
           fields=F(spec='10 uF 10 V X5R 0603', note='bulk at the HOST pads'))
    s.comp('U1', 'Sensor_Touch:AT42QT1070-S', 'AT42QT1070-SSU', (132.08, 91.44),
           nets={'1': '+3V3', '14': 'GND', '2': 'GND', '3': 'SDA', '6': 'SCL', '4': None, '5': None,
                 '13': 'KEY0', '12': 'KEY1', '11': 'KEY2', '10': 'KEY3', '9': None, '8': None, '7': None},
           footprint='Package_SO:SOIC-14_3.9x8.7mm_P1.27mm', datasheet=DS_QT,
           fields=F('AT42QT1070-SSU', 'Microchip', note='comms (I2C) mode: MODE tied to GND; I2C 0x1B; RESET, CHANGE, '
                                                         'KEY4-6 open (datasheet table 1-1)'))
    for i in range(4):
        y = 76.2 + i * 12.7
        s.comp('R%d' % (i + 1), 'Device:R', '4.7k', (180.34, y), rot=90, nets={'1': 'KEY%d' % i, '2': 'E%d' % i},
               footprint=R0603, fields=F(spec='4.7 kOhm 1% 0603', note='key series R (datasheet 3.1: ESD/RFI), next to U1'))
        s.comp('E%d' % i, 'ha_panel:TouchElectrode', 'KEY%d' % i, (215.9, y), nets={'1': 'E%d' % i},
               footprint='ha_panel:TouchElectrode_16x16mm_R2', in_bom=False,
               fields=F(note='front copper 16 x 16 r2 under the mask; viewed from the front, left to right KEY0..KEY3'))
    s.text('\n'.join([
        'AT42QT1070 (Atmel 9596C-AT42-05/2013): key outline 6 x 6 mm or larger (panel thickness dependent); plastic panels up to 5 mm;',
        '  Cx 1-30 pF per key; MODE = GND selects comms mode (rev A root cause); no pull-ups here (host 1.8 k on the Pi).',
        'Electrodes 16 x 16 mm (rev C: Ø12): QTAN0062 2.3 - electrode dimension >= 4 x panel thickness; panel = 2.5 wall + 0.7 cloth',
        '  = 3.2 mm (rev F model, not measured) -> >= 12.8 mm. Centres unchanged from rev F: front-view X 9/33/57/81, Y 13.',
        'Board 90 x 44 x 1.6 (rev F seat), no holes except tented vias; front = electrodes only; all parts and the HOST pads on the back.',
        'BME680 / VEML6030 leads now land on the main board (J10); VL53L0X cluster dropped.']),
        20.32, 160.02)


def build(out):
    import json
    kg.EXTRA_FIELDS = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bom_fields_touch.json')))  # block 3 purchase fields
    lib_path = os.path.join(out, 'lib', 'ha_panel.kicad_sym')
    lib_ha_panel.build(lib_path, which=('electrode',))
    prj = kg.Project('touch-board', out, 'HA panel touch board rev D', DATE, 'D', 'HA panel (neocleous/ha-panel)',
                     comments=['KiCad 9.0.9 - generated by hardware/main-board/gen/touch_board.py',
                               'Decision 5A (Daniel 2026-11-07): same 90 x 44 outline, electrodes + AT42QT1070 + HOST pads',
                               'Replaces hardware/rev-c (unchanged, kept for reference)'])
    prj.root.paper = 'A4'
    design(prj)
    prj.write()
    prj.write_project_files(
        sym_libs=[('ha_panel', 'lib/ha_panel.kicad_sym', 'HA panel custom symbols')],
        fp_libs=[('ha_panel', 'lib/ha_panel.pretty', 'HA panel custom footprints')])
    os.makedirs(os.path.join(out, 'lib', 'ha_panel.pretty'), exist_ok=True)
    for k in ('electrode', 'wirepads'):
        footprints.ALL[k](os.path.join(out, 'lib', 'ha_panel.pretty'))
    return prj


if __name__ == '__main__':
    build(OUT)
